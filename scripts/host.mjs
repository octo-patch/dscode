// The shared DSCODE Host: one Harness per state directory that terminals attach
// to over the local carrier socket (docs/runtime-client-design.md). `serve`
// runs it in the foreground; `start` launches it detached and waits until it
// answers; `stop` and `status` talk to it through its socket. The launcher
// calls ensureHost() before starting a separate terminal client. `dscode
// server` runs the same Host in the foreground with a TCP listener for remote
// clients (docs/remote-runtime.md).
import { closeSync, existsSync, mkdirSync, openSync, readFileSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { hostname, networkInterfaces } from 'node:os';
import { join, resolve } from 'node:path';
import { spawn } from 'node:child_process';
import { localOverlays, manifest, root, provision, runDsh, runtimeHome } from './harness.mjs';
import { PROTOCOL, callDscode, protocolCompatibility } from '../plugins/local-carrier/client.mjs';
import { runtimesFile } from './runtimes.mjs';
import { ensureSocketDirectory } from '../plugins/session-bridge/paths.mjs';

/** Exit after this long with no attached terminal and no running turn. */
export const DEFAULT_IDLE_MS = 10 * 60 * 1000;
const READY_TIMEOUT_MS = 90_000;

export const hostDirectory = (home = runtimeHome) => join(home, 'run');
// macOS caps Unix socket paths near 104 bytes, so the socket (and its lock)
// live in the session bridge's short, owner-checked per-state directory.
export const hostSocket = (home = runtimeHome) => join(ensureSocketDirectory(home), 'host.sock');
const hostLog = home => join(hostDirectory(home), 'host.log');

/** The profile overlay that turns the terminal composition into a shared Host. */
export function hostOverlay(home = runtimeHome, idleExitMs = idleMs(), { tcp, defaultCwd } = {}) {
  const remote = [
    ...(defaultCwd ? [`        defaultCwd: ${JSON.stringify(defaultCwd)}`] : []),
    ...(tcp ? [`        tcp:\n          port: ${tcp.port}\n          bind: ${JSON.stringify(tcp.bind)}\n          tokenFile: ${JSON.stringify(tcp.tokenFile)}`] : []),
  ];
  const path = join(hostDirectory(home), 'host.patch.yml');
  mkdirSync(hostDirectory(home), { recursive: true, mode: 0o700 });
  writeFileSync(path, [
    '# Generated by scripts/host.mjs: the terminal composition without its UI,',
    '# serving terminals over the local carrier. Workspace instructions, skills',
    '# and hooks are mounted per session, because one Host serves many folders.',
    '- id: tui-startup\n  disabled: true',
    '- id: tui-runner\n  disabled: true',
    '- id: dscode-hooks\n  disabled: true',
    `- insert:\n    - id: api-remotes\n      name: '@deepseek-ai/dsh-api-remotes'\n    - id: dscode-session-workspaces\n      name: ${JSON.stringify(join(root, 'plugins/desktop-workspace/index.mjs'))}\n    - id: local-carrier\n      name: ${JSON.stringify(join(root, 'plugins/local-carrier/index.mjs'))}\n      config:\n        socketPath: ${JSON.stringify(hostSocket(home))}\n        host: true\n        idleExitMs: ${idleExitMs}${remote.map(line => '\n' + line).join('')}`,
  ].join('\n') + '\n', { mode: 0o600 });
  return path;
}

function idleMs() {
  const raw = Number(process.env.DSCODE_HOST_IDLE_MS);
  return Number.isFinite(raw) && raw >= 0 ? raw : DEFAULT_IDLE_MS;
}

/** The running Host's status, or undefined when nothing answers on its socket. */
export async function hostStatus(home = runtimeHome, timeoutMs = 2000) {
  if (!existsSync(hostSocket(home))) return undefined;
  try {
    return await callDscode(hostSocket(home), 'host/status', {}, AbortSignal.timeout(timeoutMs));
  } catch { return undefined; }
}

/** Run the Host in the foreground until it exits; resolves with its exit code. */
export function serve({ home = runtimeHome, args = [], idleExitMs = idleMs(), tcp, defaultCwd } = {}) {
  provision(home, { cwd: home });
  const overlay = hostOverlay(home, idleExitMs, { tcp, defaultCwd });
  // DSCODE_HOST_PATCH adds one trusted overlay after the Host's own (verification fixtures).
  const extra = process.env.DSCODE_HOST_PATCH ? ['--patch', process.env.DSCODE_HOST_PATCH] : [];
  const child = runDsh([...localOverlays(), '--patch', overlay, ...extra, ...args], { home, cwd: home, env: { DSCODE_SESSION_WORKSPACES: '1' } });
  for (const signal of ['SIGTERM', 'SIGHUP', 'SIGINT']) process.on(signal, () => child.kill(signal));
  return new Promise(resolve => {
    child.on('error', error => { console.error(error.message); resolve(1); });
    child.on('exit', (code, signal) => resolve(code ?? (signal ? 1 : 0)));
  });
}

/** The command that launches `dscode host serve` the same way the user launches dscode. */
function serveCommand() {
  const cli = process.env.DSCODE_CLI_PATH;
  // A self-contained package goes through its own launcher, which holds the
  // installation lock and run lease for the Host's lifetime.
  return cli ? [cli, ['host', 'serve']] : [process.execPath, [join(root, 'bin/dscode.mjs'), 'host', 'serve']];
}

/**
 * Return the socket of a running Host, starting one detached when none answers.
 * @throws when a started Host does not answer within the timeout; the error
 * carries the tail of its log.
 */
export async function ensureHost({ home = runtimeHome, version = manifest.version } = {}) {
  const running = await hostStatus(home);
  if (running !== undefined) {
    const decision = runningHostDecision(running, { version });
    if (decision.action === 'attach') return hostSocket(home);
    if (decision.action === 'refuse') throw Error(decision.reason);
    await stop({ home });
  }
  mkdirSync(hostDirectory(home), { recursive: true, mode: 0o700 });
  const launch = () => {
    const log = openSync(hostLog(home), 'a', 0o600);
    const [command, args] = serveCommand();
    const state = { exited: false };
    try {
      const child = spawn(command, args, { cwd: home, detached: true, stdio: ['ignore', log, log], env: process.env });
      child.on('exit', () => { state.exited = true; });
      child.unref();
    } finally { closeSync(log); }
    return state;
  };
  let current = launch();
  const deadline = Date.now() + READY_TIMEOUT_MS;
  while (Date.now() < deadline) {
    if (await hostStatus(home) !== undefined) return hostSocket(home);
    // A Host that lost the lock race (to a concurrent start, or to one still
    // shutting down) exits at once; start again unless someone else answers.
    if (current.exited) { await new Promise(resolve => setTimeout(resolve, 300)); if (await hostStatus(home) === undefined) current = launch(); }
    await new Promise(resolve => setTimeout(resolve, 200));
  }
  if (await hostStatus(home) !== undefined) return hostSocket(home);
  const tail = existsSync(hostLog(home)) ? readFileSync(hostLog(home), 'utf8').split('\n').slice(-20).join('\n') : '';
  throw Error(`the DSCODE Host did not start (log: ${hostLog(home)})${tail ? `\n${tail}` : ''}`);
}

/**
 * What to do with a Host already answering on this state directory's socket.
 * Another installation sharing the directory (the desktop app's runtime beside
 * the terminal's, say) may have started it, so it may speak another protocol.
 * @returns `attach`; `replace` when it is idle and incompatible, or idle on an
 * older minor; or `refuse` with a reason when it is incompatible and in use.
 */
export function runningHostDecision(status, { version = manifest.version, protocol } = {}) {
  const compatibility = protocolCompatibility(status, { version, ...(protocol === undefined ? {} : { protocol }) });
  const idle = status.clients === 0 && status.running === 0;
  if (compatibility.compatible) return { action: compatibility.hostBehind && idle ? 'replace' : 'attach' };
  if (idle) return { action: 'replace' };
  return { action: 'refuse', reason: `the running DSCODE Host (pid ${status.pid}) ${compatibility.reason}; it is in use, so exit its sessions or run \`dscode host stop\`` };
}

/** Ask the Host to exit and wait until its socket stops answering. */
const alive = pid => { try { process.kill(pid, 0); return true; } catch (error) { return error.code === 'EPERM'; } };

/** Ask the Host to exit and wait until its process is gone, so a new Host can take the lock. */
export async function stop({ home = runtimeHome, timeoutMs = 30_000 } = {}) {
  const status = await hostStatus(home);
  if (status === undefined) return false;
  await callDscode(hostSocket(home), 'host/shutdown', {}).catch(() => {});
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (await hostStatus(home, 500) === undefined && !alive(status.pid)) return true;
    await new Promise(resolve => setTimeout(resolve, 200));
  }
  throw Error('the DSCODE Host did not stop in time');
}

/** Where `dscode server` keeps its bearer token (0600, inside the 0700 run directory). */
export const serverTokenFile = (home = runtimeHome) => join(hostDirectory(home), 'server-token');

/** The server token: `wanted` replaces it, `rotate` mints a new one, otherwise the stored one is reused. */
export function serverToken(home = runtimeHome, { wanted, rotate = false } = {}) {
  const file = serverTokenFile(home);
  mkdirSync(hostDirectory(home), { recursive: true, mode: 0o700 });
  if (wanted !== undefined) {
    if (wanted.length < 16 || /\s/.test(wanted)) throw Error('--token needs at least 16 characters and no spaces');
    writeFileSync(file, wanted + '\n', { mode: 0o600 });
    return wanted;
  }
  if (!rotate && existsSync(file)) {
    const stored = readFileSync(file, 'utf8').trim();
    if (stored.length >= 16) return stored;
  }
  const minted = `dsk_${randomBytes(24).toString('base64url')}`;
  writeFileSync(file, minted + '\n', { mode: 0o600 });
  return minted;
}

/** Parse `dscode server` arguments. */
export function parseServerArgs(argv) {
  const options = { bind: '0.0.0.0', rotate: false };
  for (let i = 0; i < argv.length; i++) {
    const flag = argv[i], next = () => {
      const value = argv[++i];
      if (value === undefined || value.startsWith('--')) throw Error(`${flag} needs a value`);
      return value;
    };
    if (flag === '--port') {
      const port = Number(next());
      if (!Number.isInteger(port) || port < 1 || port > 65535) throw Error('--port must be a TCP port number (1-65535)');
      options.port = port;
    } else if (flag === '--bind') options.bind = next();
    else if (flag === '--token') options.token = next();
    else if (flag === '--new-token') options.rotate = true;
    else if (flag === '--cwd') options.cwd = resolve(next());
    else if (flag === '--help' || flag === '-h') return { help: true };
    else throw Error(`unknown option ${flag}\n${SERVER_USAGE}`);
  }
  if (options.port === undefined) throw Error(`--port is required\n${SERVER_USAGE}`);
  return options;
}

const SERVER_USAGE = 'Usage: dscode server --port PORT [--bind ADDRESS] [--cwd DIR] [--token TOKEN | --new-token]';

/** Addresses a remote client could use to reach `bind`. */
function reachableAddresses(bind) {
  if (bind !== '0.0.0.0' && bind !== '::') return [bind];
  const found = Object.values(networkInterfaces()).flat().filter(entry => entry && entry.family === 'IPv4' && !entry.internal).map(entry => entry.address);
  return found.length > 0 ? found : ['<server-address>'];
}

/** `dscode server`: the Host in the foreground, serving remote clients over TCP until stopped. */
export async function server(argv, { home = runtimeHome } = {}) {
  const options = parseServerArgs(argv);
  if (options.help) { console.log(SERVER_USAGE); return 0; }
  const running = await hostStatus(home);
  if (running !== undefined) {
    // An idle background Host would hold the lock; one with work is the user's to stop.
    if (running.clients > 0 || running.running > 0) throw Error(`a DSCODE Host (pid ${running.pid}) is serving terminals in this state directory; exit them or run \`dscode host stop\`, then start the server`);
    await stop({ home });
  }
  const token = serverToken(home, { wanted: options.token, rotate: options.rotate });
  const defaultCwd = options.cwd ?? process.cwd();
  const alias = hostname().split('.')[0].toLowerCase().replace(/[^a-z0-9-]/g, '-') || 'server';
  console.log([
    `DSCODE server on ${options.bind}:${options.port} (default folder ${defaultCwd})`,
    'Traffic is NOT encrypted: use it on a trusted network (VPN, Tailscale, LAN) or through an SSH tunnel.',
    'Connect a client with:',
    ...reachableAddresses(options.bind).map(address => `  dscode config --runtime ${address}:${options.port} --token ${token} --alias ${alias} --set-default`),
    `The token is stored in ${serverTokenFile(home)}; --new-token replaces it.`,
  ].join('\n'));
  return serve({ home, idleExitMs: 0, defaultCwd, tcp: { port: options.port, bind: options.bind, tokenFile: serverTokenFile(home) } });
}

/**
 * Where this installation keeps its Host and runtimes, for clients other than
 * the terminal (the desktop app) that drive the launcher instead of
 * re-deriving its paths.
 */
export const location = (home = runtimeHome) => ({ home, socket: hostSocket(home), runtimes: runtimesFile(home), version: manifest.version, protocol: PROTOCOL });

export async function main(argv = process.argv.slice(2)) {
  const [command = 'status', ...rest] = argv;
  if (command === 'serve') { process.exitCode = await serve({ args: rest }); return; }
  if (command === 'start') {
    const socket = await ensureHost();
    console.log(rest.includes('--json') ? JSON.stringify({ ...location(), socket }) : `DSCODE Host ready: ${socket}`);
    return;
  }
  if (command === 'locate') { console.log(JSON.stringify(location())); return; }
  if (command === 'stop') { console.log(await stop() ? 'DSCODE Host stopped' : 'no DSCODE Host is running'); return; }
  if (command === 'status') {
    const status = await hostStatus();
    if (status === undefined) { console.log('no DSCODE Host is running'); process.exitCode = 3; return; }
    console.log(JSON.stringify(status, null, 2));
    return;
  }
  throw Error('Usage: dscode host [status|start [--json]|stop|serve|locate]');
}
